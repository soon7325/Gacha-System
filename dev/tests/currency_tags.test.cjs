const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
let language='zh', locked=false, dirty=0;
const root={innerHTML:'',querySelectorAll:()=>[]};
const context=require('./icon_test_context.cjs').createContext({window:{},document:{getElementById:()=>root},gameId:'tags',getLang:()=>language,
    gameInfo:{categories:[{id:'mount',name:'坐骑'}],globalTiers:[],tagDefinitions:{limited:{name:'限定',en:'Limited'},standard:{name:'常驻',en:'Standard'}},
        economy:{resources:[{id:'token',name:'代币'}],incomes:[{id:'return',name:'返还',resourceId:'token',source:'byproduct',amount:5,condition:'overflow',categoryId:'mount'},{id:'gift',name:'赠送',resourceId:'token',source:'gift',schedule:'once',amount:1}]}},
    readEngineEdit:()=> '[]',GameData:{getPresetRules:()=>null},sessionStorage:{getItem:()=>null},galleryPreviewLock:{isLocked:()=>locked},markPageDirty:()=>dirty++});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../../pages/gallery_economy.js'),'utf8'),context);
const economy=context.window.GalleryEconomy, row=context.gameInfo.economy.incomes[0];
economy.render();
assert.deepEqual(Array.from(row.tagIds),[],'旧规则默认不限制');
assert.equal(row.tagMatch,'any');
assert.match(root.innerHTML,/data-eco-tag-match hidden/);
assert.equal((root.innerHTML.match(/data-eco-multi="tagIds"/g)||[]).length,1,'仅返还规则显示标签条件');
assert.match(root.innerHTML,/value="limited"/);
assert.match(root.innerHTML,/value="standard"/);
const summary={textContent:'',title:''}, boxes=[{value:'',checked:true},{value:'limited',checked:false},{value:'standard',checked:false}];
const group={querySelectorAll:()=>boxes,querySelector:()=>summary};
const matchField={hidden:true};
const card={dataset:{ecoList:'incomes',ecoId:'return'},querySelector:selector=>selector==='[data-eco-tag-match]'?matchField:null};
const changeTag=(value,checked)=>{
    const control={type:'checkbox',value,checked,dataset:{ecoField:'tagIds'},closest:selector=>selector==='[data-eco-field]'?control:selector==='[data-eco-list]'?card:selector==='[data-eco-multi]'?group:null};
    root.onchange({target:control});
};
changeTag('limited',true);
assert.equal(matchField.hidden,true,'单选时隐藏匹配方式');
changeTag('standard',true);
assert.equal(matchField.hidden,false,'多选时立即显示，不重建标签菜单');
assert.deepEqual(Array.from(row.tagIds),['limited','standard']);
assert.equal(row.categoryId,'mount','更改标签不清除大类条件');
assert.equal(summary.textContent,'限定、常驻');
assert.equal(boxes[0].checked,false);
const mode={type:'select-one',tagName:'SELECT',value:'all',dataset:{ecoField:'tagMatch'},setCustomValidity(){},closest:selector=>selector==='[data-eco-field]'?mode:selector==='[data-eco-list]'?card:null};
root.onchange({target:mode});
assert.equal(row.tagMatch,'all');
changeTag('standard',false);
assert.equal(matchField.hidden,true);
assert.equal(row.tagMatch,'all','隐藏时保留原匹配方式');
changeTag('standard',true);
assert.equal(matchField.hidden,false);
assert.deepEqual(Array.from(economy.validate()),[]);
const restored=JSON.parse(JSON.stringify(context.gameInfo.economy));
assert.deepEqual(restored.incomes[0].tagIds,['limited','standard']);
assert.equal(restored.incomes[0].tagMatch,'all');
language='en';economy.render();
assert.match(root.innerHTML,/Pulled item tags/);
assert.match(root.innerHTML,/Limited/);
assert.match(root.innerHTML,/Match all tags/);
context.gameInfo.tagDefinitions.limited.en='Event only';economy.render();
assert.match(root.innerHTML,/Event only/,'名称跟随图鉴标签定义');
delete context.gameInfo.tagDefinitions.limited;
assert.ok(economy.validate().some(error=>error.includes('removed tag')),'标签被删除时不默默放宽范围');
assert.deepEqual(Array.from(row.tagIds),['limited','standard']);
locked=true;const previousDirty=dirty;
changeTag('',true);
assert.equal(dirty,previousDirty);
assert.equal(row.tagIds.length,2);
locked=false;changeTag('',true);
assert.deepEqual(Array.from(row.tagIds),[]);
assert.equal(boxes[0].checked,true);
assert.equal(matchField.hidden,true,'不限制时隐藏匹配方式');
assert.equal(summary.textContent,'Unrestricted');
assert.deepEqual(Array.from(economy.validate()),[],'不限制时不受已删除标签影响');
context.gameInfo.tagDefinitions={};economy.render();
assert.match(root.innerHTML,/Add options in the catalog settings first/);
// 单条规则分别保存未溢出（含首次）和溢出数量，不影响既有条件。
mode.dataset.ecoField='condition';mode.value='cap_split';
root.onchange({target:mode});
assert.equal(row.overflowAmount,5,'首次启用分段时沿用当前数量');
assert.match(root.innerHTML,/data-eco-field="overflowAmount"/);
assert.match(root.innerHTML,/including first/);
const overflow={type:'number',tagName:'INPUT',value:'20',min:'1',max:'',dataset:{ecoField:'overflowAmount'},setCustomValidity(){},closest:selector=>selector==='[data-eco-field]'?overflow:selector==='[data-eco-list]'?card:null};
root.oninput({type:'input',target:overflow});
assert.equal(row.amount,5);
assert.equal(row.overflowAmount,20);
assert.deepEqual(Array.from(economy.validate()),[]);
row.overflowAmount=0;
assert.ok(economy.validate().some(error=>error.includes('Overflow amounts')));
row.overflowAmount=20;
const splitSaved=JSON.parse(JSON.stringify(row));
assert.equal(splitSaved.condition,'cap_split');
assert.equal(splitSaved.amount,5);
assert.equal(splitSaved.overflowAmount,20);
mode.value='non_overflow';root.onchange({target:mode});
assert.doesNotMatch(root.innerHTML,/data-eco-field="overflowAmount"/);
assert.equal(row.overflowAmount,20,'切换条件保留已填写的溢出数量');
mode.value='cap_split';root.onchange({target:mode});
assert.equal(row.overflowAmount,20);
locked=true;mode.value='always';root.onchange({target:mode});
assert.equal(row.condition,'cap_split');
console.log('PASS：标签默认不限制、多选、任一/全部、双语、持久化、删除引用保护与只读保护');
