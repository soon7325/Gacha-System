/** Run `node dev/tools/build-home-assets.cjs` after adding homepage images. No build server required. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const folder = path.join(root, 'img/OTHER/index');
const groups = new Map();
for (const file of fs.readdirSync(folder).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))) {
    const match = file.match(/^([a-z0-9]+)[ _-]+(?:(NEW)[ _-]*)?(\d*)(?:[ _-]+(en|zh|both))?\.(png|jpe?g|webp|avif)$/i);
    if (!match || (!match[2] && !match[3])) continue;
    const prefix = match[1].toUpperCase();
    if (!groups.has(prefix)) groups.set(prefix, []);
    groups.get(prefix).push({ src: 'img/OTHER/index/' + file, latest: !!match[2],
        language: match[4]?.toLowerCase() || 'both',
        key: `${match[2] ? 'new' : 'base'}:${Number(match[3] || 1)}` });
}
const games = [...groups].map(([prefix, images]) => ({
    id: prefix.toLowerCase(), prefix,
    icon: fs.existsSync(path.join(root, 'img', prefix, 'icon/game_icon.webp')) ? `img/${prefix}/icon/game_icon.webp` : null,
    images
}));
fs.writeFileSync(path.join(root, 'pages/home-assets.js'),
    '// Generated by dev/tools/build-home-assets.cjs. Do not edit by hand.\nwindow.HOME_GAME_ASSETS = ' + JSON.stringify(games, null, 2) + ';\n');
console.log(`Homepage assets: ${games.length} games, ${games.reduce((n, game) => n + game.images.length, 0)} images.`);
